# Generates critical_path.dot (activity-on-node CPM network) from tab:cpm in Chapter-3-3.
# Edit ACTS below, run `python gen_critical_path.py`, then `neato -n2 -Tpng critical_path.dot -o ../critical_path.png`
# (neato is used only to honour the fixed node positions; -n2 keeps them as given).
ACTS = {  # id: (name line 1, name line 2, modules, weeks, predecessors)
    'A': ('Requirements, backlog', 'and architecture', '--', 4, []),
    'B': ('Authentication and', 'device binding', 'M1', 4, ['A']),
    'C': ('User and role', 'management', 'M7', 2, ['A']),
    'D': ('Exam creation', 'and eligibility', 'M8, M9', 4, ['B', 'C']),
    'E': ('Readiness check, student', 'dashboard and lockdown', 'M2-M4', 4, ['D']),
    'F': ('Monitoring client and live', 'proctoring dashboard', 'M5, M10', 4, ['E']),
    'G': ('Submission, backup and', 'AI-assisted evaluation', 'M6, M11', 4, ['F']),
    'H': ('Audit logs, analytics', 'and reports', 'M12', 4, ['G']),
    'I': ('Integration, testing,', 'documentation and demo', 'All', 4, ['H']),
}
ACCENT, GREY, DARK = '#B03A2E', '#8C8C8C', '#333333'
# forward / backward pass
es, ef = {}, {}
for k, (_, _, _, d, pre) in ACTS.items():
    es[k] = max([ef[p] for p in pre], default=0); ef[k] = es[k] + d
end = max(ef.values())
succ = {k: [s for s, v in ACTS.items() if k in v[4]] for k in ACTS}
lf, ls = {}, {}
for k in reversed(list(ACTS)):
    lf[k] = min([ls[s] for s in succ[k]], default=end); ls[k] = lf[k] - ACTS[k][3]
fl = {k: ls[k] - es[k] for k in ACTS}
crit = {k for k in ACTS if fl[k] == 0}
path = [k for k in ACTS if k in crit]
assert end == 32 and path == list('ABDEFGHI') and fl['C'] == 2, (end, path, fl)

S = 72  # points per inch
pos = {'Start': (0.4, 4.0), 'A': (2.05, 4.0), 'B': (4.75, 5.1), 'C': (4.75, 3.05),
       'D': (7.45, 4.0), 'E': (10.15, 4.0),
       'F': (2.05, 0.55), 'G': (4.75, 0.55), 'H': (7.45, 0.55), 'I': (10.15, 0.55),
       'End': (11.85, 0.55)}
W = 172  # width (pt) of the activity text cell

def label(k):
    n1, n2, mods, d, _ = ACTS[k]
    c = ACCENT if k in crit else GREY
    b = 2 if k in crit else 1
    idc = f'<FONT COLOR="{ACCENT}"><B>{k}</B></FONT>' if k in crit else f'<B>{k}</B>'
    flt = f'<B>Float {fl[k]}</B>' if fl[k] else f'Float {fl[k]}'
    return (f'<<TABLE BORDER="{b}" COLOR="{c}" CELLBORDER="1" CELLSPACING="0" CELLPADDING="3" BGCOLOR="white">'
            f'<TR><TD WIDTH="{W//3}">ES {es[k]}</TD><TD WIDTH="{W//3}" BGCOLOR="#EEEEEE"><B>{d} wk</B></TD><TD WIDTH="{W//3}">EF {ef[k]}</TD></TR>'
            f'<TR><TD COLSPAN="3" WIDTH="{W}"><FONT POINT-SIZE="15">{idc}</FONT><BR/>{n1}<BR/>{n2}<BR/>'
            f'<FONT COLOR="#555555"><I>Modules: {mods}</I></FONT></TD></TR>'
            f'<TR><TD>LS {ls[k]}</TD><TD BGCOLOR="#EEEEEE">{flt}</TD><TD>LF {lf[k]}</TD></TR></TABLE>>')

out = ['digraph CPM {',
       '  // GENERATED by gen_critical_path.py -- edit the script, not this file.',
       '  graph [splines=line, outputorder=edgesfirst, bgcolor=white, dpi=150, pad=0.15,',
       '         fontname="Arial", fontsize=17, labelloc=t, label=<<B>Critical Path Network (activity on node, durations in weeks)</B>>];',
       '  node  [fontname="Arial", fontsize=12, shape=plain];',
       '  edge  [arrowsize=0.8];']
for k in ACTS:
    x, y = pos[k]; out.append(f'  {k} [pos="{x*S:.0f},{y*S:.0f}", label={label(k)}];')
for k in ('Start', 'End'):
    x, y = pos[k]
    out.append(f'  {k} [pos="{x*S:.0f},{y*S:.0f}", shape=circle, width=0.62, fixedsize=true, style=filled, '
               f'fillcolor="{ACCENT}", color="{ACCENT}", fontcolor=white, fontsize=11, label=<<B>{k}</B>>];')

def edge(a, b, critical, head=True):
    st = f'color="{ACCENT}", penwidth=2.6' if critical else f'color="{GREY}", penwidth=1.4, style=dashed'
    out.append(f'  {a} -> {b} [{st}{"" if head else ", arrowhead=none"}];')

edge('Start', 'A', True)
for k, v in ACTS.items():
    for p in v[4]:
        if (p, k) == ('E', 'F'):
            continue
        edge(p, k, p in crit and k in crit)
edge('I', 'End', True)
# E -> F wraps from the end of row 1 to the start of row 2 through way-points
wp = [(10.15, 1.85), (0.4, 1.85), (0.4, 0.55)]
for i, (x, y) in enumerate(wp):
    out.append(f'  wp{i} [pos="{x*S:.0f},{y*S:.0f}", shape=point, width=0.01, label=""];')
edge('E', 'wp0', True, False); edge('wp0', 'wp1', True, False); edge('wp1', 'wp2', True, False); edge('wp2', 'F', True)
legend = (f'<<TABLE BORDER="0" CELLSPACING="2" CELLPADDING="1">'
          f'<TR><TD ALIGN="LEFT"><FONT COLOR="{ACCENT}"><B>Critical path: {" - ".join(path)} = {end} weeks (8 sprints x 4 weeks).</B></FONT>'
          f'  Dashed: non-critical; C (2 weeks, with B) has 2 weeks of float.</TD></TR>'
          f'<TR><TD ALIGN="LEFT">Node key: ES/EF, LS/LF = earliest/latest start and finish in weeks elapsed (0 = project start); top centre = duration, bottom centre = float.</TD></TR></TABLE>>')
out.append(f'  legend [pos="{6.1*S:.0f},{-0.75*S:.0f}", shape=plain, fontsize=12, label={legend}];')
out.append('}')
open('critical_path.dot', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('ES', es, '\nLS', ls, '\nfloat', fl)
