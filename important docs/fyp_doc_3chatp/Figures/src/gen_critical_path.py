# Generates critical_path.dot (activity-on-node CPM network) from tab:cpm in Chapter-3-3.
# Edit ACTS below, run `python -I gen_critical_path.py` in this folder, then
#   neato -n2 -Tpng critical_path.dot -o ../critical_path.png
# (neato is used only to honour the fixed node positions; -n2 keeps them as given).
# Layout: three columns, read as a snake (row 1 left to right, row 2 right to left,
# row 3 left to right). Fonts are 14 pt on a canvas about 800 pt wide, so the text
# prints at about 7.5 pt at 0.95\linewidth.
ACTS = {  # id: (name line 1, name line 2, modules, weeks, predecessors)
    'A': ('Requirements, backlog', 'and architecture', '--', 4, []),
    'B': ('Authentication and', 'device binding', 'M1', 4, ['A']),
    'C': ('User and role', 'management', 'M7', 2, ['A']),
    'D': ('Exam creation', 'and eligibility', 'M8, M9', 4, ['B', 'C']),
    'E': ('Readiness check, student', 'dashboard and lockdown', 'M2-M4', 4, ['D']),
    'F': ('Monitoring client and live', 'proctoring dashboard', 'M5, M10', 4, ['E']),
    'G': ('Submission, backup and', 'AI-assisted evaluation', 'M6, M11', 4, ['F']),
    'H': ('Hash-chained audit log,', 'analytics and reports', 'M12', 4, ['G']),
    'I': ('Integration, testing,', 'documentation and demo', 'All', 4, ['H']),
}
ACCENT, GREY, DARK = '#B03A2E', '#8C8C8C', '#333333'
# forward / backward pass
es, ef = {}, {}
for k, (_, _, _, d, pre) in ACTS.items():
    es[k] = max([ef[p] for p in pre], default=0); ef[k] = es[k] + d
end = max(ef.values())
succ = {k: [s for s, v in ACTS.items() if k in v[4]] for k in ACTS}
lf, ls = {}, {}
for k in reversed(list(ACTS)):
    lf[k] = min([ls[s] for s in succ[k]], default=end); ls[k] = lf[k] - ACTS[k][3]
fl = {k: ls[k] - es[k] for k in ACTS}
crit = {k for k in ACTS if fl[k] == 0}
path = [k for k in ACTS if k in crit]
# the critical path must be the longest path: check it against every Start-to-End chain
def longest(k):
    return ACTS[k][3] + max([longest(s) for s in succ[k]], default=0)
assert longest('A') == end == 32 and path == list('ABDEFGHI') and fl['C'] == 2, (end, path, fl)

W = 204          # width (pt) of the activity text cell
X1, X2, X3 = 172, 442, 712           # column centres (pt)
Y1, Y2, Y3 = 538, 270, 82            # row centres (pt): row 1 (A, D), row 2, row 3
pos = {'Start': (X1, Y1 + 145), 'A': (X1, Y1), 'B': (X2, Y1 + 80), 'C': (X2, Y1 - 80), 'D': (X3, Y1),
       'E': (X3, Y2), 'F': (X2, Y2), 'G': (X1, Y2),
       'H': (X1, Y3), 'I': (X2, Y3), 'End': (X3, Y3)}

def label(k):
    n1, n2, mods, d, _ = ACTS[k]
    c = ACCENT if k in crit else GREY
    b = 2 if k in crit else 1
    idc = f'<FONT COLOR="{ACCENT}"><B>{k}</B></FONT>' if k in crit else f'<B>{k}</B>'
    flt = f'<B>Float {fl[k]}</B>' if fl[k] else f'Float {fl[k]}'
    return (f'<<TABLE BORDER="{b}" COLOR="{c}" CELLBORDER="1" CELLSPACING="0" CELLPADDING="3" BGCOLOR="white">'
            f'<TR><TD WIDTH="{W//3}">ES {es[k]}</TD><TD WIDTH="{W//3}" BGCOLOR="#EEEEEE"><B>{d} wk</B></TD><TD WIDTH="{W//3}">EF {ef[k]}</TD></TR>'
            f'<TR><TD COLSPAN="3" WIDTH="{W}"><FONT POINT-SIZE="18">{idc}</FONT><BR/>{n1}<BR/>{n2}<BR/>'
            f'<FONT COLOR="#555555"><I>Modules: {mods}</I></FONT></TD></TR>'
            f'<TR><TD>LS {ls[k]}</TD><TD BGCOLOR="#EEEEEE">{flt}</TD><TD>LF {lf[k]}</TD></TR></TABLE>>')

out = ['digraph CPM {',
       '  // GENERATED by gen_critical_path.py -- edit the script, not this file.',
       '  graph [splines=line, outputorder=edgesfirst, bgcolor=white, dpi=150, pad=0.12,',
       '         fontname="Arial", fontsize=18, labelloc=t, label=<<B>Critical Path Network (activity on node, weeks)</B>>];',
       '  node  [fontname="Arial", fontsize=14, shape=plain];',
       '  edge  [arrowsize=0.9];']
for k in ACTS:
    x, y = pos[k]; out.append(f'  {k} [pos="{x},{y}", label={label(k)}];')
for k in ('Start', 'End'):
    x, y = pos[k]
    out.append(f'  {k} [pos="{x},{y}", shape=circle, width=0.72, fixedsize=true, style=filled, '
               f'fillcolor="{ACCENT}", color="{ACCENT}", fontcolor=white, fontsize=14, label=<<B>{k}</B>>];')

def edge(a, b, critical):
    st = f'color="{ACCENT}", penwidth=2.6' if critical else f'color="{GREY}", penwidth=1.6, style=dashed'
    out.append(f'  {a} -> {b} [{st}];')

edge('Start', 'A', True)
for k, v in ACTS.items():
    for p in v[4]:
        edge(p, k, p in crit and k in crit)
edge('I', 'End', True)
legend = (f'<<TABLE BORDER="0" CELLSPACING="2" CELLPADDING="1">'
          f'<TR><TD ALIGN="LEFT"><FONT COLOR="{ACCENT}"><B>Critical path: {" - ".join(path)} = {end} weeks (8 sprints x 4 weeks).</B></FONT></TD></TR>'
          f'<TR><TD ALIGN="LEFT">Dashed: non-critical. C (2 weeks, beside B) has 2 weeks of float.</TD></TR>'
          f'<TR><TD ALIGN="LEFT">Node: ES/EF and LS/LF = earliest/latest start and finish (weeks elapsed);</TD></TR>'
          f'<TR><TD ALIGN="LEFT">top centre = duration, bottom centre = float.</TD></TR></TABLE>>')
out.append(f'  legend [pos="{X2},{Y3 - 128}", shape=plain, fontsize=14, label={legend}];')
out.append('}')
open('critical_path.dot', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('ES', es, '\nLS', ls, '\nfloat', fl)
